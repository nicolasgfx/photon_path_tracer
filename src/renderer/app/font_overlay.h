// ── Fill a rectangle with alpha-blended color ───────────────────────

inline void fillRect(std::vector<uint8_t>& pixels, uint32_t imgW, uint32_t imgH,
                     int x0, int y0, int x1, int y1,
                     uint8_t r, uint8_t g, uint8_t b, float alpha) {
    x0 = std::max(0, x0);
    y0 = std::max(0, y0);
    x1 = std::min(static_cast<int>(imgW), x1);
    y1 = std::min(static_cast<int>(imgH), y1);
    float ia = 1.0f - alpha;
    for (int py = y0; py < y1; ++py) {
        for (int px = x0; px < x1; ++px) {
            uint32_t pi = (static_cast<uint32_t>(py) * imgW
                         + static_cast<uint32_t>(px)) * 4;
            pixels[pi + 0] = static_cast<uint8_t>(pixels[pi + 0] * ia + r * alpha + 0.5f);
            pixels[pi + 1] = static_cast<uint8_t>(pixels[pi + 1] * ia + g * alpha + 0.5f);
            pixels[pi + 2] = static_cast<uint8_t>(pixels[pi + 2] * ia + b * alpha + 0.5f);
        }
    }
}

// ── Stamp a text string into an RGBA pixel buffer ───────────────────

inline void stampText(std::vector<uint8_t>& pixels, uint32_t imgW, uint32_t imgH,
                      const std::string& text, int startX, int startY,
                      uint8_t r, uint8_t g, uint8_t b, float alpha,
                      int scale = 1) {
    constexpr int GW = 5, GH = 7, SPACING = 1;
    int cx = startX;
    for (char c : text) {
        const uint8_t* glyph = glyphData(c);
        for (int gy = 0; gy < GH; ++gy) {
            uint8_t row = glyph[gy];
            for (int gx = 0; gx < GW; ++gx) {
                if (row & (0x80 >> gx)) {
                    for (int sy = 0; sy < scale; ++sy) {
                        for (int sx = 0; sx < scale; ++sx) {
                            int px = cx + gx * scale + sx;
                            int py = startY + gy * scale + sy;
                            if (px < 0 || px >= (int)imgW ||
                                py < 0 || py >= (int)imgH) continue;
                            uint32_t pi = (static_cast<uint32_t>(py) * imgW
                                         + static_cast<uint32_t>(px)) * 4;
                            float ia = 1.0f - alpha;
                            pixels[pi + 0] = static_cast<uint8_t>(
                                pixels[pi + 0] * ia + r * alpha + 0.5f);
                            pixels[pi + 1] = static_cast<uint8_t>(
                                pixels[pi + 1] * ia + g * alpha + 0.5f);
                            pixels[pi + 2] = static_cast<uint8_t>(
                                pixels[pi + 2] * ia + b * alpha + 0.5f);
                        }
                    }
                }
            }
        }
        cx += (GW + SPACING) * scale;
    }
}

// ── Stamp watermark (bottom-right: email) ───────────────────────────
// Improvements over v4: drop shadow, dark background bar, higher
// contrast text, minimum scale=2 for legibility.

inline void stampWatermarks(std::vector<uint8_t>& pixels, uint32_t W, uint32_t H) {
    constexpr int GW = 5, GH = 7, SPACING = 1;
    const int scale  = std::max(2, static_cast<int>(W) / 480);

    const std::string text = "drnicolasmenzel@gmail.com";

    int charW   = (GW + SPACING) * scale;
    int textH   = GH * scale;
    int textW   = static_cast<int>(text.size()) * charW;
    int margin  = 12 * scale;
    int padding = 4 * scale;

    int tx = static_cast<int>(W) - textW - margin;
    int ty = static_cast<int>(H) - textH - margin;

    // 1) Dark background bar — subtle rounded-ish rectangle
    fillRect(pixels, W, H,
             tx - padding, ty - padding,
             tx + textW + padding, ty + textH + padding,
             0, 0, 0, 0.30f);

    // 2) Drop shadow (1*scale px offset, black)
    stampText(pixels, W, H, text,
              tx + scale, ty + scale,
              0, 0, 0, 0.50f, scale);

    // 3) Foreground text (light grey, higher alpha than v4)
    stampText(pixels, W, H, text,
              tx, ty,
              220, 220, 220, 0.70f, scale);
}

